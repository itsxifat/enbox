/**
 * Builds src/features/emoji/data.js from the dataset the web client's picker uses
 * (emoji-picker-react's emojis.json, installed at the monorepo root), so the app offers the
 * same emoji, categories and order as the web.
 *
 *   npm install            # at the repo root (web workspace)
 *   node scripts/generate-emoji-data.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(import.meta.dirname, '..');
const src = path.join(root, '../node_modules/emoji-picker-react/src/data/emojis.json');
const data = JSON.parse(fs.readFileSync(src, 'utf8'));

const ORDER = [
  ['smileys_people', 'Smileys & People'],
  ['animals_nature', 'Animals & Nature'],
  ['food_drink', 'Food & Drink'],
  ['travel_places', 'Travel & Places'],
  ['activities', 'Activities'],
  ['objects', 'Objects'],
  ['symbols', 'Symbols'],
  ['flags', 'Flags'],
];

// Row: [unified, keywords, emoji version, skin-tone variations?]
const categories = ORDER.map(([id, name]) => ({
  id,
  name,
  emojis: data.emojis[id].map((e) => {
    const row = [e.u, e.n.join(','), Number(e.a)];
    if (e.v?.length) row.push(e.v);
    return row;
  }),
}));

const out = `/* Generated by scripts/generate-emoji-data.mjs from emoji-picker-react ${JSON.parse(fs.readFileSync(path.join(src, '../../../package.json'), 'utf8')).version} — do not edit. */
/* Rows: [unified codepoints, search keywords, emoji version, skin-tone variations?] */
export const CATEGORIES = ${JSON.stringify(categories)};
`;
fs.writeFileSync(path.join(root, 'src/features/emoji/data.js'), out);
console.log('src/features/emoji/data.js', (out.length / 1024).toFixed(0), 'KB');
